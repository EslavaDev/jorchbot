/**
 * System prompts for JorchBot remote operation modes.
 *
 * These prompts instruct Claude Code on how to behave when controlled
 * remotely via WhatsApp/Telegram. They are injected via --append-system-prompt.
 *
 * Phase 1 (interim): System prompts provide conversational approval.
 * Phase 2 (hooks):   PreToolUse hooks provide real tool-level approval.
 *                     These prompts still apply for UX and communication style.
 */

// ---------------------------------------------------------------------------
// Shared preamble — common to all modes
// ---------------------------------------------------------------------------

const REMOTE_PREAMBLE = [
  "You are running in REMOTE MODE. The user is controlling you from a mobile phone (WhatsApp).",
  "Respond in the SAME LANGUAGE the user writes to you.",
  "Keep messages concise — the user is reading on a small phone screen.",
  "Use short paragraphs. Avoid walls of text. Prefer structured lists.",
  "After completing actions, send a brief confirmation of what was done.",
].join("\n");

